"use client";

import { useEffect, useState } from "react";
import { ArrowUpRight, Download, RotateCcw } from "lucide-react";
import {
  CartesianGrid,
  Legend,
  Line,
  LineChart,
  ReferenceLine,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import {
  api,
  CaseId,
  Dataset,
  downloadJson,
  LiquidityInput,
  money,
  rateToPercent,
  StressDefaults,
  StressResult,
} from "@/lib/api";
import {
  StressDraft,
  stressDraftFromInput,
  stressInputFromDraft,
} from "@/lib/stress";

const labels: Record<CaseId, string> = {
  base: "Base",
  adverse: "Adverse",
  severe: "Severe",
};
const colors: Record<CaseId, string> = {
  base: "#9cc9e9",
  adverse: "#d4b488",
  severe: "#d99791",
};
const drivers = [
  [
    "cfo",
    "Operating cash flow reduction (%)",
    "Cash generated by operations, measured below the FY2025 reference.",
  ],
  [
    "capex",
    "Cash capex / FY2025 (%)",
    "Investment spending. 100% repeats the source year; 80% spends less.",
  ],
  [
    "rate",
    "New borrowing rate (%)",
    "Assumed annual coupon on the principal refinanced.",
  ],
  [
    "refinance",
    "Principal refinanced (%)",
    "The remainder of each original maturity is repaid from cash.",
  ],
  [
    "fee",
    "Issuance fee (%)",
    "An upfront cash cost applied to the amount refinanced.",
  ],
] as const;

export default function StressScenarios({
  data,
  initialDraft,
  onDraftChange,
  onOpenAnnual,
  onSources,
}: {
  data: Dataset;
  initialDraft?: StressDraft;
  onDraftChange: (draft: StressDraft) => void;
  onOpenAnnual: (
    input: LiquidityInput,
    otherCashUses: { year: number; amount: string }[],
  ) => void;
  onSources: () => void;
}) {
  const validInitial =
    initialDraft?.companyId === data.company.id &&
    initialDraft.filingId === data.financials.filing.id
      ? initialDraft
      : null;
  const [draft, setDraft] = useState<StressDraft | null>(validInitial);
  const [defaults, setDefaults] = useState<StressDefaults | null>(null);
  const [result, setResult] = useState<StressResult | null>(null);
  const [error, setError] = useState("");
  const [loadingError, setLoadingError] = useState("");
  const [busy, setBusy] = useState(true);
  const [retry, setRetry] = useState(0);
  const [editing, setEditing] = useState(false);
  const [sharedOpen, setSharedOpen] = useState(false);
  useEffect(() => {
    const controller = new AbortController();
    api<StressDefaults>(`companies/${data.company.id}/stress-defaults`, {
      signal: controller.signal,
    })
      .then((value) => {
        if (value.inputs.filing_id !== data.financials.filing.id)
          throw new Error(
            "The source snapshot changed. Reload the selected company.",
          );
        setDefaults(value);
        setDraft((current) => current ?? stressDraftFromInput(value.inputs));
      })
      .catch((e) => {
        if (!controller.signal.aborted) setLoadingError(e.message);
      });
    return () => controller.abort();
  }, [data.company.id, data.financials.filing.id, retry]);
  useEffect(() => {
    if (!draft) return;
    const controller = new AbortController();
    const timer = setTimeout(async () => {
      try {
        const input = stressInputFromDraft(draft);
        const value = await api<StressResult>("stress-tests/calculate", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(input),
          signal: controller.signal,
        });
        if (!controller.signal.aborted) setResult(value);
      } catch (e) {
        if (!controller.signal.aborted) {
          setError(e instanceof Error ? e.message : "Case calculation failed.");
          setEditing(true);
          setSharedOpen(true);
        }
      } finally {
        if (!controller.signal.aborted) setBusy(false);
      }
    }, 300);
    return () => {
      clearTimeout(timer);
      controller.abort();
    };
  }, [draft]);
  function change(next: StressDraft) {
    setResult(null);
    setError("");
    setBusy(true);
    setDraft(next);
    onDraftChange(next);
  }
  function profileChange(
    id: CaseId,
    key: "cfo" | "capex" | "rate" | "refinance" | "fee",
    value: string,
  ) {
    if (draft)
      change({
        ...draft,
        cases: draft.cases.map((profile) =>
          profile.id === id ? { ...profile, [key]: value } : profile,
        ),
      });
  }
  const selected = result?.cases.find(
    (profile) => profile.id === draft?.selected,
  );
  const chartRows = result?.cases[0].projection.years.map((year, index) =>
    Object.fromEntries([
      ["year", String(year.year)],
      ...result.cases.map((profile) => [
        profile.id,
        Number(
          profile.projection.years[index]
            .closing_cash_before_uncommitted_funding,
        ),
      ]),
    ]),
  );
  return (
    <div className="stress-workspace">
      <div className="section-intro">
        <div>
          <h2>Stress scenarios</h2>
          <p>
            See how cash generation and financing terms change the funding
            picture.
          </p>
        </div>
        <span className="assumption-label">Illustrative assumptions</span>
      </div>
      <div className="stress-context">
        <p>
          <strong>
            Historical reference: FY{data.financials.filing.fiscal_year}.
          </strong>{" "}
          Future cash flows and borrowing terms below are hypotheses. The case
          names carry no probabilities.
        </p>
        <button className="text-button" onClick={onSources}>
          Review source evidence
          <ArrowUpRight size={14} />
        </button>
      </div>
      <dl
        className="stress-source-reference"
        aria-label="Historical cash-flow reference"
      >
        {(
          [
            ["operating_cash_flow", "FY2025 operating cash flow"],
            ["capital_expenditure", "FY2025 cash capex"],
            ["cash", "FY2025 cash and equivalents"],
          ] as const
        ).map(([key, label]) => (
          <div key={key}>
            <dt>{label}</dt>
            <dd>
              {money(
                data.financials.metrics.find((metric) => metric.key === key)
                  ?.value,
                true,
                3,
              )}
            </dd>
          </div>
        ))}
      </dl>
      {loadingError && (
        <div className="information-note" role="alert">
          {loadingError}
          <button
            className="text-button"
            onClick={() => {
              setLoadingError("");
              setRetry((n) => n + 1);
            }}
          >
            Retry assumption sets
          </button>
        </div>
      )}
      {!draft && !loadingError && (
        <p role="status">Loading the source reference and assumption sets…</p>
      )}
      {draft && (
        <>
          <details
            className="panel stress-assumptions"
            open={editing}
            onToggle={(event) => setEditing(event.currentTarget.open)}
          >
            <summary>
              <strong>Edit case assumptions</strong>
              <span>Cash generation, investment and borrowing terms</span>
            </summary>
            <div className="panel-heading">
              <div>
                <span className="eyebrow">1 / CHOOSE YOUR ASSUMPTIONS</span>
                <h3>Three ways conditions could change</h3>
              </div>
              <button
                className="text-button"
                disabled={!defaults}
                onClick={() =>
                  defaults && change(stressDraftFromInput(defaults.inputs))
                }
              >
                <RotateCcw size={14} />
                Reset stress assumptions
              </button>
            </div>
            <p className="table-scroll-hint">
              Swipe the table sideways to edit all three cases.
            </p>
            <div
              className="table-scroll"
              tabIndex={0}
              role="region"
              aria-label="Editable case assumptions"
            >
              <table className="stress-driver-table">
                <thead>
                  <tr>
                    <th>Assumption</th>
                    {draft.cases.map((profile) => (
                      <th key={profile.id} className={`case-${profile.id}`}>
                        {labels[profile.id]}
                      </th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {drivers.map(([key, label, note]) => (
                    <tr key={key}>
                      <th>
                        <span>{label}</span>
                        <small>{note}</small>
                      </th>
                      {draft.cases.map((profile) => (
                        <td key={profile.id}>
                          <input
                            aria-label={`${labels[profile.id]} ${label.toLowerCase()}`}
                            inputMode="decimal"
                            maxLength={24}
                            value={profile[key]}
                            onChange={(e) =>
                              profileChange(profile.id, key, e.target.value)
                            }
                          />
                        </td>
                      ))}
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <p className="stress-reference-note">
              Each future year uses the same change relative to FY2025.
              Reductions are not compounded. Initial capex stays unchanged, so a
              weaker case does not assume that investment can be cut
              automatically.
            </p>
          </details>
          <details
            className="panel stress-shared"
            open={sharedOpen}
            onToggle={(event) => setSharedOpen(event.currentTarget.open)}
          >
            <summary>
              Shared cash settings and other outflows{" "}
              <span>{draft.horizon}-year horizon</span>
            </summary>
            <div className="stress-common-fields">
              {(
                [
                  ["opening", "Available opening cash (USDm)"],
                  ["floor", "Minimum cash floor (USDm)"],
                  ["previous", "Original coupon assumption (%)"],
                ] as const
              ).map(([key, label]) => (
                <label key={key}>
                  <span>{label}</span>
                  <input
                    aria-label={`Stress ${label.toLowerCase()}`}
                    inputMode="decimal"
                    value={draft[key]}
                    maxLength={32}
                    onChange={(e) =>
                      change({ ...draft, [key]: e.target.value })
                    }
                  />
                </label>
              ))}
              <label>
                <span>Projection horizon</span>
                <select
                  aria-label="Stress projection horizon"
                  value={draft.horizon}
                  onChange={(e) =>
                    change({ ...draft, horizon: e.target.value })
                  }
                >
                  {[1, 2, 3, 4, 5].map((n) => (
                    <option key={n} value={n}>
                      {n} {n === 1 ? "year" : "years"}
                    </option>
                  ))}
                </select>
              </label>
            </div>
            <p>
              Opening cash repeats the source balance with availability assumed.
              Adjust it for restricted access. The cash floor is a chosen
              operating reserve, not a sourced credit standard.
            </p>
            <div className="stress-other-uses">
              {draft.other.slice(0, Number(draft.horizon)).map((row, index) => (
                <label key={row.year}>
                  <span>{row.year} other uses (USDm)</span>
                  <input
                    aria-label={`Stress ${row.year} other cash uses (USDm)`}
                    inputMode="decimal"
                    value={row.value}
                    maxLength={32}
                    onChange={(e) =>
                      change({
                        ...draft,
                        other: draft.other.map((item, i) =>
                          i === index
                            ? { ...item, value: e.target.value }
                            : item,
                        ),
                      })
                    }
                  />
                </label>
              ))}
            </div>
            <p>
              Other cash uses are shared assumptions.{" "}
              {data.company.ticker === "NUE" || data.company.research_profile.short_term_outside_maturities
                ? "The initial first-year amount assumes repayment of the separate short-term balance. Its timing is hypothetical. "
                : data.company.ticker === "LECO"
                  ? "Bank debt is already included in the 2026 maturity bucket. Other initial zeros are assumptions. "
                  : "Initial zeros are explicit assumptions, not observed absence of obligations. "}
              Add lease principal, dividends, buybacks, acquisitions and other
              outflows where needed.
            </p>
          </details>
          <div
            className="stress-selection"
            role="group"
            aria-label="Selected stress case"
          >
            <span>2 / EXAMINE A CASE</span>
            <div>
              {draft.cases.map((profile) => (
                <button
                  key={profile.id}
                  className={`case-selector case-${profile.id} ${draft.selected === profile.id ? "selected" : ""}`}
                  aria-pressed={draft.selected === profile.id}
                  onClick={() => change({ ...draft, selected: profile.id })}
                >
                  {labels[profile.id]}
                </button>
              ))}
            </div>
          </div>
          <dl
            className="selected-assumptions"
            aria-label="Selected case assumptions"
          >
            {(
              [
                ["cfo", "CFO reduction"],
                ["capex", "Capex / FY2025"],
                ["rate", "New rate"],
                ["refinance", "Refinanced"],
                ["fee", "Issuance fee"],
              ] as const
            ).map(([key, label]) => (
              <div key={key}>
                <dt>{label}</dt>
                <dd>
                  {
                    draft.cases.find(
                      (profile) => profile.id === draft.selected,
                    )?.[key]
                  }
                  %
                </dd>
              </div>
            ))}
            <div>
              <dt>Original coupon</dt>
              <dd>{draft.previous}%</dd>
            </div>
          </dl>
        </>
      )}
      {error && (
        <div className="information-note" role="alert">
          {error}
        </div>
      )}
      {busy && draft && (
        <p role="status">Calculating each case and the sensitivity grid…</p>
      )}
      {result && selected && (
        <>
          {!result.assumptions_ordered_by_severity && (
            <p className="information-note">
              Your edited assumption sets are not consistently ordered by
              severity. Compare their inputs and results directly.
            </p>
          )}
          <div
            className="stress-result-summary"
            aria-label={`${selected.label} case result`}
          >
            <div>
              <span>
                {selected.label} · cash at end of{" "}
                {selected.projection.years.at(-1)?.year}
              </span>
              <strong data-testid="stress-ending-cash">
                {money(
                  selected.projection.closing_cash_before_uncommitted_funding,
                  true,
                  2,
                )}
              </strong>
              <small>Before uncommitted funding</small>
            </div>
            <div>
              <span>Peak shortfall to your cash floor</span>
              <strong data-testid="stress-peak-shortfall">
                {money(selected.projection.peak_shortfall, true, 2)}
              </strong>
              <small>
                Chosen cash floor: {money(result.inputs.minimum_cash, true, 2)}
              </small>
            </div>
            <div>
              <span>First year below your cash floor</span>
              <strong data-testid="stress-first-shortfall">
                {selected.projection.first_shortfall_year ??
                  "None in this model"}
              </strong>
              <small>Year-end balances only</small>
            </div>
          </div>
          <div className="stress-conclusion">
            <span className="eyebrow">WHAT THIS RESULT MEANS</span>
            <p data-testid="stress-explanation">{selected.explanation}</p>
            <p className="field-note">
              These outcomes depend on the displayed cash flows, other uses and
              refinancing assumptions. Unentered distributions, acquisitions and
              lease-principal payments remain excluded. A cash shortfall remains
              unfunded in the model.
            </p>
          </div>
          <section className="panel stress-chart-panel">
            <div className="panel-heading">
              <h3>Cash under each set of assumptions</h3>
              <span className="unit-note">
                USD · year-end · before uncommitted funding
              </span>
            </div>
            <div
              className="stress-chart"
              role="img"
              aria-label="Base, Adverse and Severe year-end cash projections"
            >
              <ResponsiveContainer width="100%" height={300}>
                <LineChart
                  data={chartRows}
                  margin={{ top: 15, right: 24, bottom: 12, left: 14 }}
                >
                  <CartesianGrid
                    stroke="#3b4550"
                    strokeDasharray="2 4"
                    vertical={false}
                  />
                  <XAxis dataKey="year" stroke="#aebdcb" tickLine={false} />
                  <YAxis
                    stroke="#aebdcb"
                    width={85}
                    tickLine={false}
                    tickFormatter={(v) => money(String(v))}
                  />
                  <ReferenceLine
                    y={Number(result.inputs.minimum_cash)}
                    stroke="#b4bcc5"
                    strokeDasharray="3 3"
                  />
                  <Tooltip
                    formatter={(value, name) => [
                      money(String(value), false),
                      labels[name as CaseId] ?? String(name),
                    ]}
                    contentStyle={{
                      background: "#1b2128",
                      border: "1px solid #586b7b",
                      color: "#e4ebf2",
                    }}
                  />
                  <Legend
                    formatter={(name) => labels[name as CaseId] ?? name}
                  />
                  {result.cases.map((profile) => (
                    <Line
                      key={profile.id}
                      dataKey={profile.id}
                      type="linear"
                      stroke={colors[profile.id]}
                      strokeWidth={profile.id === selected.id ? 3 : 1.5}
                      strokeDasharray={
                        profile.id === "adverse"
                          ? "6 3"
                          : profile.id === "severe"
                            ? "2 3"
                            : undefined
                      }
                      dot={{ r: 3 }}
                      isAnimationActive={false}
                    />
                  ))}
                </LineChart>
              </ResponsiveContainer>
            </div>
            <p className="table-scroll-hint">
              Swipe the table sideways to compare all three cases.
            </p>
            <div
              className="table-scroll"
              tabIndex={0}
              role="region"
              aria-label="Three-case comparison results"
            >
              <table className="stress-comparison-table">
                <caption className="sr-only">
                  Case results for the selected source snapshot
                </caption>
                <thead>
                  <tr>
                    <th>Result</th>
                    {result.cases.map((profile) => (
                      <th key={profile.id}>{profile.label}</th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <th>Ending cash, before gap funding</th>
                    {result.cases.map((profile) => (
                      <td key={profile.id}>
                        {money(
                          profile.projection
                            .closing_cash_before_uncommitted_funding,
                          true,
                          2,
                        )}
                      </td>
                    ))}
                  </tr>
                  <tr>
                    <th>Peak shortfall to cash floor</th>
                    {result.cases.map((profile) => (
                      <td key={profile.id}>
                        {money(profile.projection.peak_shortfall, true, 2)}
                      </td>
                    ))}
                  </tr>
                  <tr>
                    <th>First shortfall year</th>
                    {result.cases.map((profile) => (
                      <td key={profile.id}>
                        {profile.projection.first_shortfall_year ??
                          "None in horizon"}
                      </td>
                    ))}
                  </tr>
                  <tr>
                    <th>Assumed principal refinanced</th>
                    {result.cases.map((profile) => (
                      <td key={profile.id}>
                        {money(
                          profile.projection.total_refinanced_principal,
                          true,
                          2,
                        )}
                      </td>
                    ))}
                  </tr>
                </tbody>
              </table>
            </div>
          </section>
          <div className="stress-analysis-grid">
            <section className="panel">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">3 / FOLLOW THE DIFFERENCE</span>
                  <h3>Why cash changes versus Base</h3>
                </div>
              </div>
              {selected.id === "base" ? (
                <p className="stress-empty-comparison">
                  Base is the comparison reference. Select Adverse or Severe to
                  see the contributions to their different ending cash.
                </p>
              ) : (
                <div className="table-scroll">
                  <table className="stress-contributions">
                    <thead>
                      <tr>
                        <th>Assumption effect</th>
                        <th>Cash change</th>
                      </tr>
                    </thead>
                    <tbody>
                      {selected.cash_change_drivers.map((driver) => (
                        <tr key={driver.key}>
                          <td>{driver.label}</td>
                          <td>{money(driver.amount, true, 2)}</td>
                        </tr>
                      ))}
                      <tr className="stress-driver-total">
                        <th>Ending cash change vs Base</th>
                        <td data-testid="stress-cash-change">
                          {money(selected.ending_cash_change_vs_base, true, 2)}
                        </td>
                      </tr>
                    </tbody>
                  </table>
                </div>
              )}
              <p className="stress-reference-note">
                Negative contributions reduce cash relative to Base; positive
                ones offset the reduction. Lower refinancing can save coupon
                costs while requiring more principal to be paid from cash.
              </p>
            </section>
            <section className="panel stress-sensitivity">
              <div className="panel-heading">
                <div>
                  <span className="eyebrow">4 / CHANGE TWO DRIVERS</span>
                  <h3>Rate and cash-flow sensitivity</h3>
                </div>
              </div>
              <p className="stress-reference-note">
                Cells show peak shortfall to the cash floor. Other inputs stay
                at the selected {selected.label} settings. The blue outline
                marks the current pair.
              </p>
              <p className="table-scroll-hint">
                Swipe the grid sideways to see every borrowing rate.
              </p>
              <div
                className="table-scroll"
                tabIndex={0}
                role="region"
                aria-label="Cash-flow and borrowing-rate sensitivity"
              >
                <table>
                  <caption>
                    Rows: CFO reduction · Columns: new borrowing rate
                  </caption>
                  <thead>
                    <tr>
                      <th>CFO reduction</th>
                      {result.rate_axis.map((rate) => (
                        <th key={rate}>{rateToPercent(rate)}%</th>
                      ))}
                    </tr>
                  </thead>
                  <tbody>
                    {result.cfo_axis.map((decline) => (
                      <tr key={decline}>
                        <th>{rateToPercent(decline)}%</th>
                        {result.rate_axis.map((rate) => {
                          const cell = result.sensitivity_cells.find(
                            (c) =>
                              c.cfo_decline_fraction === decline &&
                              c.new_rate === rate,
                          )!;
                          return (
                            <td
                              key={rate}
                              className={`${cell.is_selected ? "sensitivity-current" : ""} ${cell.first_shortfall_year !== null ? "sensitivity-shortfall" : ""}`}
                              data-testid={
                                cell.is_selected
                                  ? "sensitivity-selected"
                                  : undefined
                              }
                              title={
                                cell.reason ??
                                (cell.first_shortfall_year
                                  ? `First shortfall: ${cell.first_shortfall_year}`
                                  : "No year-end shortfall in horizon")
                              }
                            >
                              {cell.available ? (
                                money(cell.peak_shortfall, true, 1)
                              ) : (
                                <span
                                  tabIndex={0}
                                  aria-label={cell.reason ?? "Unavailable"}
                                >
                                  Unavailable
                                </span>
                              )}
                            </td>
                          );
                        })}
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </section>
          </div>
          <div className="stress-actions">
            <button
              className="primary-button"
              onClick={() =>
                onOpenAnnual(
                  selected.resolved_inputs,
                  result.inputs.other_cash_uses,
                )
              }
            >
              Explore {selected.label} year by year
              <ArrowUpRight size={15} />
            </button>
            <button
              className="secondary-button"
              onClick={() =>
                downloadJson(
                  result,
                  `refilens-${data.company.ticker.toLowerCase()}-stress-cases.json`,
                )
              }
            >
              <Download size={14} />
              Export stress cases JSON
            </button>
          </div>
          <p className="stress-scope-note">
            Outside this horizon: {money(result.excluded_principal, false)} of
            disclosed principal ({result.excluded_bucket_labels.join(", ")}).
            Those buckets remain unallocated. Source amounts retain their
            original rounding.
          </p>
          <details className="panel stress-method">
            <summary>How to read these cases and their limits</summary>
            {defaults?.rationale.map((text) => (
              <p key={text}>{text}</p>
            ))}
            {result.notes.map((text) => (
              <p key={text}>{text}</p>
            ))}
          </details>
        </>
      )}
    </div>
  );
}
